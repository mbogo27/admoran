// Generates src/lib/frames.generated.ts from the single source of truth,
// src/content/_zoom.yaml. Run before build/dev so content.config.ts can
// import a plain .ts array instead of parsing YAML at schema-definition time.
// See spec §8.2: there must be exactly one file defining the frame vocabulary.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parse } from 'yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const raw = readFileSync(join(root, 'src/content/_zoom.yaml'), 'utf-8');
const config = parse(raw);
const frameIds = Object.keys(config.frames);

const out = `// AUTO-GENERATED by scripts/gen-frames-enum.mjs from src/content/_zoom.yaml
// Do not hand-edit. Run \`node scripts/gen-frames-enum.mjs\` (or pnpm build) to regenerate.
export const FRAMES = [${frameIds.map((f) => `'${f}'`).join(', ')}] as const;
export type FrameId = (typeof FRAMES)[number];
`;

mkdirSync(join(root, 'src/lib'), { recursive: true });
writeFileSync(join(root, 'src/lib/frames.generated.ts'), out);
console.log(`Generated src/lib/frames.generated.ts with ${frameIds.length} frames: ${frameIds.join(', ')}`);
